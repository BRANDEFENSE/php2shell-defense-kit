"""Replay the lab's request shapes through ModSecurity v3 (official owasp/modsecurity-crs:nginx image) with the bundled third-party rules.
MIT License, Copyright (c) 2026 Brandefense.
Developer/provenance tool (needs the lab folder). usage: python3 -I modsec_run.py <lab-dir>
The container runs --network none; nginx with ModSecurity listens on 127.0.0.1:8081 and proxies to a static 200 server on 9999
inside the same container; the requests are sent with the container's curl. DetectionOnly, audit log in JSON.
Request bodies are regenerated by the lab's own generators into a temporary folder and deleted afterwards (the corpus stores none)."""
import json, shutil, subprocess, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_corpus as B

HERE = Path(__file__).resolve().parent
KIT = HERE.parents[1]
ORDER = ["hdr600k", "leak", "benign", "health", "hdrcount", "reqparse", "progress", "nextreq"]

def main(lab):
    lab = Path(lab).resolve()
    W = lab / "results/engines/modsec"
    shutil.rmtree(W, ignore_errors=True)
    (W / "bodies").mkdir(parents=True); (W / "out").mkdir()
    rec = B.record_requests(B.load_drive(lab))
    plan = []
    for sc in ORDER:
        for (m, p, body, h, label) in rec[sc]:
            plan.append((sc, m, p, body, h, label))
        plan.append((sc, "GET", "/target.php", None, {}, "health after scenario"))
    cmds, meta = [], []
    for i, (sc, m, p, body, h, label) in enumerate(plan):
        a = ["curl", "-s", "-o", "/dev/null", "-m", "60", "-X", m, "-H", "X-Lab-Seq: %d" % i]
        for k, v in h.items():
            a += ["-H", "%s: %s" % (k, v)]
        if body:
            (W / "bodies" / ("%d.bin" % i)).write_bytes(body)
            a += ["--data-binary", "@/work/bodies/%d.bin" % i]
        a.append("http://127.0.0.1:8081" + p)
        cmds.append(" ".join("'%s'" % x for x in a))
        meta.append(dict(seq=i, scenario=sc, method=m, path=p.split("?")[0], step=label))
    (W / "plan.json").write_text(json.dumps(meta, indent=1))
    rules = "\n".join(Path(KIT / x).read_text() for x in (
        "third_party/break-the-build__php-multipart-waf-signals/modsecurity/php-multipart-signals.conf",
        "third_party/orbitron-ai__php2shell-response-kit/rules/modsecurity/php2shell-upload-progress.conf"))
    (W / "main.conf").write_text("""SecRuleEngine DetectionOnly
SecRequestBodyAccess On
SecRequestBodyLimit 13107200
SecRequestBodyNoFilesLimit 131072
SecRequestBodyLimitAction Reject
SecAuditEngine On
SecAuditLog /work/out/audit.json
SecAuditLogFormat JSON
SecAuditLogParts ABIFHZ
SecDebugLog /work/out/debug.log
SecDebugLogLevel 0
""" + rules)
    (W / "nginx.conf").write_text("""load_module /etc/nginx/modules/ngx_http_modsecurity_module.so;
user root; worker_processes 1; daemon off; error_log /work/out/error.log notice; pid /tmp/nginx.pid;
events { worker_connections 64; }
http { client_max_body_size 0; client_body_temp_path /tmp/c; proxy_temp_path /tmp/p; fastcgi_temp_path /tmp/f; uwsgi_temp_path /tmp/u; scgi_temp_path /tmp/s;
  access_log /work/out/access.log;
  server { listen 127.0.0.1:8081; modsecurity on; modsecurity_rules_file /work/main.conf; location / { proxy_pass http://127.0.0.1:9999; } }
  server { listen 127.0.0.1:9999; location / { return 200 "ok\\n"; } } }
""")
    (W / "run.sh").write_text("#!/bin/sh\nnginx -c /work/nginx.conf &\nsleep 3\n" + "\n".join(cmds) + "\nsleep 2\npkill nginx\nsleep 1\n")
    r = subprocess.run(["docker", "run", "--rm", "--network", "none", "-v", "%s:/work" % W, "--entrypoint", "sh",
                        "owasp/modsecurity-crs:nginx", "/work/run.sh"], capture_output=True, text=True)
    print(r.returncode, r.stderr[-300:])
    shutil.rmtree(W / "bodies")

if __name__ == "__main__":
    main(sys.argv[1])
